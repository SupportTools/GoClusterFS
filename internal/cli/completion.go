package cli

import (
	"flag"
	"fmt"
	"io"
	"sort"
	"strings"
)

// Completion kinds for flag values and positional arguments.
const (
	CompleteNone = ""
	CompleteFile = "file"
	CompleteDir  = "dir"
)

// CompletionSpec says how to complete a command's flag values and positional arguments.
type CompletionSpec struct {
	Values     map[string]string // flag name to CompleteFile or CompleteDir
	Positional string            // CompleteFile for a device argument, or CompleteNone
}

// WriteCompletion writes a bash or zsh completion script for prog built from fs.
func WriteCompletion(w io.Writer, shell, prog string, fs *flag.FlagSet, spec CompletionSpec) error {
	switch shell {
	case "bash":
		return writeBash(w, prog, fs, spec)
	case "zsh":
		return writeZsh(w, prog, fs, spec)
	}
	return fmt.Errorf("unknown shell %q; use bash or zsh", shell)
}

func takesValue(f *flag.Flag) bool {
	b, ok := f.Value.(interface{ IsBoolFlag() bool })
	return !ok || !b.IsBoolFlag()
}

func writeBash(w io.Writer, prog string, fs *flag.FlagSet, spec CompletionSpec) error {
	var names []string
	kinds := map[string][]string{}
	fs.VisitAll(func(f *flag.Flag) {
		names = append(names, "-"+f.Name)
		if takesValue(f) {
			kinds[spec.Values[f.Name]] = append(kinds[spec.Values[f.Name]], "-"+f.Name)
		}
	})
	fn := "_" + strings.NewReplacer("-", "_", ".", "_").Replace(prog)
	var b strings.Builder
	fmt.Fprintf(&b, "# bash completion for %s, generated by %s -completion bash\n", prog, prog)
	fmt.Fprintf(&b, "%s() {\n\tlocal cur=\"${COMP_WORDS[COMP_CWORD]}\" prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n\tcase \"$prev\" in\n", fn)
	for _, k := range []struct{ kind, gen string }{{CompleteFile, "-f"}, {CompleteDir, "-d"}} {
		if len(kinds[k.kind]) > 0 {
			sort.Strings(kinds[k.kind])
			fmt.Fprintf(&b, "\t%s)\n\t\tCOMPREPLY=($(compgen %s -- \"$cur\"))\n\t\treturn\n\t\t;;\n", strings.Join(kinds[k.kind], "|"), k.gen)
		}
	}
	if len(kinds[CompleteNone]) > 0 {
		sort.Strings(kinds[CompleteNone])
		fmt.Fprintf(&b, "\t%s)\n\t\treturn\n\t\t;;\n", strings.Join(kinds[CompleteNone], "|"))
	}
	fmt.Fprintf(&b, "\tesac\n\tif [[ \"$cur\" == -* ]]; then\n\t\tCOMPREPLY=($(compgen -W \"%s\" -- \"$cur\"))\n\t\treturn\n\tfi\n", strings.Join(names, " "))
	if spec.Positional == CompleteFile {
		b.WriteString("\tCOMPREPLY=($(compgen -f -- \"$cur\"))\n")
	}
	fmt.Fprintf(&b, "}\ncomplete -o filenames -F %s %s\n", fn, prog)
	_, err := io.WriteString(w, b.String())
	return err
}

func writeZsh(w io.Writer, prog string, fs *flag.FlagSet, spec CompletionSpec) error {
	var b strings.Builder
	fmt.Fprintf(&b, "#compdef %s\n# zsh completion for %s, generated by %s -completion zsh\n\n_arguments \\\n", prog, prog, prog)
	fs.VisitAll(func(f *flag.Flag) {
		opt := fmt.Sprintf("-%s[%s]", f.Name, zshDescription(f.Usage))
		if takesValue(f) {
			switch spec.Values[f.Name] {
			case CompleteFile:
				opt += ":file:_files"
			case CompleteDir:
				opt += ":directory:_files -/"
			default:
				opt += ":value: "
			}
		}
		fmt.Fprintf(&b, "  %s \\\n", zshQuote(opt))
	})
	if spec.Positional == CompleteFile {
		b.WriteString("  '1:device:_files'\n")
	} else {
		b.WriteString("  && return 0\n")
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// zshDescription shortens a flag's usage to its first clause for the completion menu.
func zshDescription(usage string) string {
	if i := strings.IndexAny(usage, ";."); i > 0 {
		usage = usage[:i]
	}
	if len(usage) > 70 {
		usage = strings.TrimSpace(usage[:67]) + "..."
	}
	return strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`).Replace(usage)
}

func zshQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
